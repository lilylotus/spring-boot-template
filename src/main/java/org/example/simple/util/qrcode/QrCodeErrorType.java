package org.example.simple.util.qrcode;

/**
 * 二维码生成错误类别，便于调用方区分编码、字体和写出失败。
 * <p>
 * 该分类用于程序化判断，不建议调用方解析异常消息文本。
 */
public enum QrCodeErrorType {

    /** 文本无法按所选纠错等级或字符集编码为二维码。 */
    ENCODING,
    /** 中间提示文本包含当前字体无法显示的字符。 */
    FONT,
    /** 待解码字节不是可识别的图片，或图片中未找到可识别的二维码，或找到但内容无法通过校验。 */
    DECODING,
    /** 读写目标文件或输出流时发生 I/O 错误。 */
    IO
}
